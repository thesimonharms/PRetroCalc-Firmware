def pack_rows(rows):
    assert len(rows) == 16
    out = []
    for r in rows:
        assert len(r) == 16, (len(r), r)
        lo = hi = 0
        for i, c in enumerate(r):
            if c in "X#@*":
                if i < 8:
                    lo |= 1 << i
                else:
                    hi |= 1 << (i - 8)
        out += [lo, hi]
    return out

def pad16(rows):
    rows = [("." * 16 if (not r or r == "") else r) for r in rows]
    while len(rows) < 16:
        rows.append("." * 16)
    return rows[:16]

