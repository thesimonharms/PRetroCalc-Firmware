def main():
    lines = [
        "/* Auto-generated 16x16 Aksara Jawa font. bit0=left. 2 bytes/row LE. */",
        '#include "font_jawa.h"',
        "#include <stdbool.h>",
        "",
        "const uint8_t font_jawa[JAWA_COUNT][JAWA_BYTES] = {",
    ]
    for i in range(0xA9E0 - 0xA980):
        cp = 0xA980 + i
        art = G.get(cp, BLANK)
        # allow empty strings in put() as blank rows
        art = [("." * 16 if r == "" else r) for r in art]
        art = pad16(art)
        data = pack_rows(art)
        hx = ",".join(f"0x{b:02X}" for b in data)
        lines.append(f"    {{{hx}}}, /* U+{cp:04X} */")
    lines += [
        "};",
        "",
        "const uint8_t *font_jawa_glyph(uint32_t cp) {",
        "    if (cp < JAWA_CP_MIN || cp > JAWA_CP_MAX) return 0;",
        "    return font_jawa[cp - JAWA_CP_MIN];",
        "}",
        "",
        "bool font_jawa_is_mark(uint32_t cp) {",
        "    return (cp >= 0xA980 && cp <= 0xA983) ||",
        "           (cp >= 0xA9B3 && cp <= 0xA9C0);",
        "}",
        "",
        "int font_jawa_advance(uint32_t cp) {",
        "    if (font_jawa_is_mark(cp)) return 0;",
        "    if (cp >= JAWA_CP_MIN && cp <= JAWA_CP_MAX) return JAWA_W;",
        "    return 0;",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(G)} designed, 96 slots)")

if __name__ == "__main__":
    main()
